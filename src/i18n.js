/** Texte traduit ; `{nom}` est remplacé par vars.nom. */
export function t(key, vars) {
  let s = D[lang][key];
  if (s == null) s = D.en[key];
  if (s == null) s = key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ''));
  return s;
}
