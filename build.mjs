// Génère main.js à partir de src/ (three.js est inclus dans le fichier).
// Utilisation : npm install puis npm run build
import * as esbuild from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const dir = path.dirname(fileURLToPath(import.meta.url));
const nodePaths = process.env.C3D_NODE_PATH ? [process.env.C3D_NODE_PATH] : [];

await esbuild.build({
  entryPoints: [path.join(dir, 'src/main.js')],
  outfile: path.join(dir, 'main.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: ['obsidian', 'electron', '@codemirror/*', '@lezer/*'],
  minify: true,
  legalComments: 'none',
  nodePaths,
  banner: { js: '/* Axon Mind — generated by build.mjs from src/ (bundles three.js, MIT licence). */' },
  logLevel: 'info',
});
